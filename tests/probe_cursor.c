/* p98_quit()が本当にカーソルを表示へ戻すかどうかの実測用プローブ。
 *
 * p98_quit()の直後、このプログラム自身はまだ実行中でCOMMAND.COMへは
 * 戻っていない。この「戻る前」の状態でしばらく待つことで、
 * 「p98_quit()自身がカーソルを表示に戻したか」を、
 * 「COMMAND.COMがプロンプト表示時にカーソルを出す」という別の副作用
 * (実測で確認: これがあるため、DOSプロンプトへ戻った後でカーソル状態を
 * 見ても、p98_quit()自身が復帰させたのか単にCOMMAND.COMが出し直したのか
 * 区別できない)と混同せずに確認する。
 */
#include "p98.h"

int main(void) {
    int i;
    p98_init();
    p98_quit();
    /* まだCOMMAND.COMへ戻らず、ここでしばらく静止する(約2秒、
     * p98_wait_vsync()はp98_quit()後も動く低レベルなVSYNCポーリングなので
     * 使える)。 tools/verify.mjs はこの間にカーソル状態を読む。 */
    for (i = 0; i < 120; i++) {
        p98_wait_vsync();
    }
    return 0;
}
