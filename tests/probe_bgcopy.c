/* p98_copy_bgpage_to_screen()(src/p98.c、2026-09後半、背景ページ→画面ページの
 * まるごとコピー)の正しさを検査するプローブ。probe_bgpage.cと同じ「VRAMを
 * 直接読んで判定する」方式。
 *
 * 背景ページへ非一様なパターン(色の違う矩形を複数、画面の最上端行(y=0)・
 * 中央付近・最下端行(y=396-399、画面全体コピーが1行でも欠けると壊れる
 * ぎりぎりの位置)まで含めて)敷き、画面ページには背景と明確に異なる色
 * (画面全体をp98_clear(6)で塗る)を先に描いておいてから、
 * p98_copy_bgpage_to_screen()を呼ぶ。
 *
 * 陽性対照はこのファイル自体の中に2つ入っている:
 *   1. 背景パターンは単色の塗りつぶしではない(複数の異なる色を使う)ため、
 *      コピーが「常に同じ値を書く」ような故障をしていても検出できる。
 *   2. 画面ページの元の色(6=赤+緑)は背景パターンのどの矩形の色とも異なる
 *      ため、コピーが実際に起きていなければ画面側にはこの色が残るはずで、
 *      tools/verify.mjsが「コピー前の色が残っていないこと」を別途確認する
 *      (=コピーが本当に効いていることの確認)。
 */
#include "p98.h"

static void draw_background_pattern(void) {
    p98_clear(0);
    p98_fill_rect(0, 0, 640, 4, 10);     /* 最上端(y=0-3)、赤+輝度 */
    p98_fill_rect(0, 200, 640, 8, 5);    /* 中央付近(y=200-207)、青+緑 */
    p98_fill_rect(200, 100, 64, 32, 12); /* 単発矩形(y=100-131)、緑+輝度 */
    p98_fill_rect(0, 396, 640, 4, 9);    /* 最下端(y=396-399)、青+輝度 */
}

int main(void) {
    p98_init_bgpage();

    p98_set_draw_target(P98_TARGET_BACKGROUND);
    draw_background_pattern();

    p98_set_draw_target(P98_TARGET_SCREEN);
    p98_clear(6); /* 背景のどこにも使っていない色(赤+緑)。コピー前の画面はこれ。 */

    p98_copy_bgpage_to_screen();

    for (;;) { }
    return 0;
}
