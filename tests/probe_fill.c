/* p98_fill_rect() の実測用プローブ。
 * 3つの矩形を描いたあと無限ループへ入り、CPUを止めてVRAMを読める状態を保つ。
 *   矩形A: (8,8,16,8) color=15  ... バイト境界に揃った矩形
 *   矩形B: (100,40,13,5) color=5 ... バイト境界からずれた矩形(左右端がビット単位)
 *   矩形C: (630,10,30,10) color=10 ... 右端が画面外(640超)にはみ出す。
 *          クリップが効いていれば x=630..639 だけが塗られ、次の行(row=11)の
 *          先頭バイトは触られない。クリップを外すとオフセット計算が
 *          行をまたいで隣の行の先頭バイトまで書き込んでしまう。
 */
#include "p98.h"

int main(void) {
    p98_init();
    /* p98_init()直後は描画ページが裏(非表示)側になっている設計なので、
     * 表側(=セグメント先頭がそのまま0xA8000等になり、外部からreadMemoryで
     * 素直に読める側)へ一度flipしてから描く。裏ページの物理アドレスは
     * バンク切り替え方式の疑いがあり(docs/verify-log.md参照)、このテストの
     * 対象(塗り・クリップ)には関係が無いので混同を避ける。 */
    p98_flip();
    p98_clear(0);
    p98_fill_rect(8, 8, 16, 8, 15);
    p98_fill_rect(100, 40, 13, 5, 5);
    p98_fill_rect(630, 10, 30, 10, 10);
    for (;;) { }
    return 0;
}
