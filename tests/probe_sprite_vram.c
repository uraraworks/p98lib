/* p98_vram_upload()/p98_draw_sprite_vram()/p98_vram_reupload() の
 * CPU経路(p98_draw_sprite())との等価性プローブ。
 *
 * 同じスプライトデータを同じ座標(横位置のずれdxだけ変える)でCPU経路と
 * VRAM/EGC経路の両方に描き、tools/verify.mjs 側がVRAMのバイト列を
 * 突き合わせる。座標はすべてこのファイルのコメントに明記する
 * (ホスト側=tools/verify.mjsが読む場所と対応させるため)。
 *
 * 背景は p98_fill_rect(0,0,640,400,BG_COLOR) を最初に1回だけ敷く
 * (BG_COLOR=9=0b1001=B,Iプレーンが1、R,Gプレーンが0。透明ドットの位置で
 * 背景が残っていることが見える色にするため、0以外を選ぶ)。
 *
 * ---- スプライト定義 ----
 * SPR_A: 16x16、全ドット不透明(mask=all 0xFF)。4プレーンとも別々の値
 *   (色が混ざる絵)。1行=2バイト。
 * SPR_B: 32x32、マスクに穴がある(透明ドットを含む)。各行のマスクは
 *   0x7E,0xFF,0xFF,0x7E で、左端(byte0のbit7=col0)と右端(byte3のbit0=
 *   col31)が透明になっている(byte0のbit0=col7、byte3のbit7=col24も
 *   ついでに透明)。4プレーン(B_BLUE/B_RED/B_GREEN/B_INT)は内容を
 *   変えてあり、B_BLUE/B_INTは透明ドットの位置にもわざと1を混ぜてある
 *   (p98_vram_upload()の「絵をmaskとANDしてから書く」修正の確認用。
 *   効いていないと透明ドットの位置でCPU経路とVRAM/EGC経路の結果が
 *   ずれるはず)。さらにB_BLUE/B_INTは不透明領域の一部(byte1/byte2)を
 *   あえて0にしてある(背景色BG_COLORのB/Iプレーンは1なので、
 *   p98_draw_sprite_vram()のパス1(AND、背景を0にする)を省くとパス2の
 *   OR転送で背景の1が残ってしまい、CPU経路の結果とずれる。
 *   tests/p98_broken_vram_noand.c の検出用)。
 *
 * ---- レイアウト(すべて背景色BG_COLORの上に描く。ブロックはYで
 *      重ならないよう積み上げ、端のテストだけXを離して置く) ----
 *
 * ブロックA(SPR_A、dx=0..15、8列x2行、列間隔48、word境界X0=16+col*48):
 *   CPU: y = 8  + row*20   (row=dx/8, col=dx%8, x = X0+dx)
 *   EGC: y = 56 + row*20
 *
 * ブロックB(SPR_B、dx=0..15、8列x2行、列間隔64、word境界X0=16+col*64):
 *   CPU: y = 104 + row*36
 *   EGC: y = 184 + row*36
 *
 * 端(SPR_A、xが負/右端はみ出し。どちらもp98_draw_sprite_vram内部で
 *   p98_draw_sprite()へフォールバックするはず):
 *   CPU: (-5,264) と (632,264)
 *   EGC: (-5,284) と (632,284)
 *
 * 再アップロード確認(SPR_B、p98_vram_reupload()で置き直した後に描画):
 *   CPU: (16,308)
 *   EGC: (16,344)
 *
 * 端(SPR_B、yが上下にはみ出す位置。X=560(CPU)/608(EGC)、どちらも
 *   word境界でdx=0固定):
 *   上: (560,-5) / (608,-5)
 *   下: (560,392) / (608,392)
 */
