static const p98_sprite_t SPR_B = { 32, 32, { B_BLUE, B_RED, B_GREEN, B_INT }, B_MASK };

int main(void) {
    p98_vram_sprite_t vsA, vsB;
    int dx, col, row;

    p98_init();
    p98_flip();

    p98_fill_rect(0, 0, 640, 400, BG_COLOR); /* 背景(0以外)を1回だけ敷く */

    p98_vram_reset();
    p98_vram_upload(&SPR_A, &vsA);
    p98_vram_upload(&SPR_B, &vsB);

    /* ブロックA: SPR_A、dx=0..15、8列x2行、列間隔48。 */
    for (dx = 0; dx < 16; dx++) {
        col = dx % 8;
        row = dx / 8;
        p98_draw_sprite(&SPR_A, 16 + col * 48 + dx, 8 + row * 20);
        p98_draw_sprite_vram(&vsA, 16 + col * 48 + dx, 56 + row * 20);
    }

    /* ブロックB: SPR_B、dx=0..15、8列x2行、列間隔64。 */
    for (dx = 0; dx < 16; dx++) {
        col = dx % 8;
        row = dx / 8;
        p98_draw_sprite(&SPR_B, 16 + col * 64 + dx, 104 + row * 36);
        p98_draw_sprite_vram(&vsB, 16 + col * 64 + dx, 184 + row * 36);
    }

    /* 端: xが負 / 右端はみ出し(SPR_A、フォールバック確認)。 */
    p98_draw_sprite(&SPR_A, -5, 264);
    p98_draw_sprite_vram(&vsA, -5, 284);
    p98_draw_sprite(&SPR_A, 632, 264);
    p98_draw_sprite_vram(&vsA, 632, 284);

    /* 再アップロード確認: SPR_Bを置き直した後にもう一度描く。 */
    p98_vram_reupload(&vsB, &SPR_B);
    p98_draw_sprite(&SPR_B, 16, 308);
    p98_draw_sprite_vram(&vsB, 16, 344);

    /* 端: yが上下にはみ出す位置(SPR_B、X=560(CPU)/608(EGC)、dx=0固定)。 */
    p98_draw_sprite(&SPR_B, 560, -5);
    p98_draw_sprite_vram(&vsB, 608, -5);
    p98_draw_sprite(&SPR_B, 560, 392);
    p98_draw_sprite_vram(&vsB, 608, 392);

    for (;;) { }
    return 0;
}
