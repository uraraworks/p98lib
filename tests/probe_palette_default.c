/* 起動直後(p98lib のプログラムを1本も走らせていないFreeDOS)のパレット既定値
 * 実測用プローブ。
 *
 * p98_init()はパレットへ一切書き込まない(読み出して退避するだけ、
 * かつその退避先はここでは使わない)ので、ここで見えている16本の帯の色は
 * ハードウェア/BIOSが起動時に設定した「本当の既定パレット」そのものである
 * ことが保証される。p98_quit()は意図的に呼ばない(呼ぶとパレットへ書き込みが
 * 発生し、以後に他のプログラムを走らせたときの既定値観測が汚れるため)。
 *
 * 帯は幅40ドット(=640/16、8の倍数でバイト境界に揃う)、高さ40ドットを
 * 画面上端(y=0)に並べる。tools側はcanvasの各帯の中央付近1点をサンプルし、
 * 4bit値0..15それぞれの実際のRGB(0-255)を得る。
 */
#include "p98.h"

int main(void) {
    int i;
    p98_init();
    /* p98_init()直後は draw_page=1 / disp_page=0 (flip前提の初期状態、
     * docs/design.md参照)。ここでは「見た目」を測りたいので、まず
     * draw_page(=1)へ描いてから p98_flip() で disp_page 側へ回す
     * (probe_fill.c 等のVRAMバイト直読み検証とは逆順。あちらはホスト側の
     * readMemory がセグメント0xA8000経由でdraw_pageのバンクを直接読める
     * ことだけが目的で、実際に画面へ表示されているかは見ていない)。 */
    for (i = 0; i < 16; i++) {
        p98_fill_rect(i * 40, 0, 40, 40, i);
    }
    p98_flip();
    for (;;) { p98_wait_vsync(); }
    return 0;
}
